function account(name) {
    const result = spawnSync('getent', ['passwd', name], { encoding: 'utf8' });
    if (result.status !== 0)
        run('useradd', ['-m', '-s', '/bin/bash', '-c', 'Tuxee prototype test', name]);
    const fields = run('getent', ['passwd', name]).split(':');
    assert.equal(fields[4], 'Tuxee prototype test', 'refusing unrelated account');
    const password = randomBytes(24).toString('base64url');
    run('chpasswd', [], `${name}:${password}\n`);
    return { name, password, uid: Number(fields[2]), gid: Number(fields[3]), home: fields[5] };
}
