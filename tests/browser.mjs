async function checkGridDragLayers() {
    const layers = await page.locator('.grid-stack').evaluate(grid => {
        const panels = [...grid.querySelectorAll(':scope > [data-panel]')];
        const overlays = [...grid.querySelectorAll(':scope > .grid-vacancy, :scope > .dock-preview')];
        return {
            isolated: getComputedStyle(grid).isolation === 'isolate',
            above: overlays.length > 0 && overlays.every(overlay => panels.every(panel =>
                Number(getComputedStyle(overlay).zIndex) > (Number(getComputedStyle(panel).zIndex) || 0))),
            opacity: Number(getComputedStyle(document.querySelector('.panel-dragging')).opacity),
            neighborsOpaque: panels.filter(panel => !panel.classList.contains('panel-dragging')).every(panel => getComputedStyle(panel).opacity === '1'),
        };
    });
    assert.deepEqual(layers, { isolated: true, above: true, opacity: .8, neighborsOpaque: true }, 'grid overlays stay above every window and only the dragged window is translucent');
}
